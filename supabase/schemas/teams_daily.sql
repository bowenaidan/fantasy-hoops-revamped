create table public.teams_daily (
  team_id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  team_name character varying null,
  team_points smallint null,
  manager_name character varying null,
  potential_points smallint null,
  earned_points boolean null,
  constraint teams_pkey primary key (team_id)
) TABLESPACE pg_default;