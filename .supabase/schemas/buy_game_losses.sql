create table public.buy_game_losses (
  game_id integer generated by default as identity not null,
  team_loser text null,
  score_loser smallint null,
  conference_loser text null,
  team_winner text null,
  score_winner smallint null,
  conference_winner text null,
  game_date date null,
  created_at timestamp with time zone not null default now(),
  constraint buy_game_losses_pkey primary key (game_id)
) TABLESPACE pg_default;