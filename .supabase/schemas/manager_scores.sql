create table public.manager_scores (
  manager_id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  official_score smallint null,
  today_score smallint null,
  previous_rank smallint null,
  current_rank smallint null,
  record character varying null,
  constraint manager_scores_pkey primary key (manager_id)
) TABLESPACE pg_default;