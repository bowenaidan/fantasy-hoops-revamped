create table public.game_history (
  game_id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  team_home character varying null,
  score_home smallint null,
  conference_home character varying null,
  rank_home smallint null,
  winner_home boolean null,
  team_away character varying null,
  score_away smallint null,
  conference_away character varying null,
  rank_away smallint null,
  winner_away boolean null,
  constraint game_history_pkey primary key (game_id)
) TABLESPACE pg_default;